const handler = async (m, { command }) => {
    const now = new Date();

    switch (command) {
        case 'الوقت': case 'الساعة': {
            const time = now.toLocaleTimeString('ar-EG', { hour: '2-digit', minute: '2-digit', second: '2-digit' });
            return m.reply(`⏰ *الساعة دلوقتي:* ${time}\n_يلا يا صايع، الوقت بيجري._`);
        }

        case 'تاريخ_اليوم': {
            const date = now.toLocaleDateString('ar-EG', { year: 'numeric', month: 'long', day: 'numeric' });
            return m.reply(`📅 *النهاردة:* ${date}`);
        }

        case 'اليوم': {
            const day = now.toLocaleDateString('ar-EG', { weekday: 'long' });
            return m.reply(`🗓️ *يوم:* ${day} يا لورد.`);
        }

        case 'نكتة_تقنية': {
            return m.reply(`😂 *نكتة السيستم:*\n${pick(JOKES)}`);
        }

        case 'حكمة': {
            return m.reply(`🧠 *حكمة اليوم:*\n${pick(WISDOM)}`);
        }

        case 'اقتباس_ملوكي': {
            return m.reply(`💬 *اقتباس ملوكي:*\n${pick(QUOTES)}`);
        }

        case 'معلومة_تقنية': {
            return m.reply(`📡 *معلومة هتعجبك:*\n${pick(FACTS)}`);
        }

        case 'تحفيز': {
            return m.reply(`🔥 *دفعة تحفيز:*\n${pick(MOTIVATION)}`);
        }

        case 'مود_البوت': {
            const moods = ['😎 رايق ومظبوط 100%','🔥 شغال بأقصى طاقة','🥱 شوية كسلان بس بخدمك','👑 ملوكي زي دايمًا','⚡ سريع زي البرق'];
            return m.reply(`🤖 *مود البوت دلوقتي:* ${pick(moods)}`);
        }

        case 'فكرة_اليوم': {
            const ideas = [
                'اليوم جرب تتعلم حاجة جديدة في الكود، ولو سطر واحد بس.',
                'كلم صاحبك اللي زعلان منك، السيستم بينصحك بكده.',
                'اعمل باكاب لحاجة مهمة عندك، متندمش بعدين.',
                'خد بريك من الشاشة ربع ساعة، هتفرق معاك كتير.'
            ];
            return m.reply(`💡 *فكرة اليوم:*\n${pick(ideas)}`);
        }
    }
};

handler.usage = ['الوقت','تاريخ_اليوم','اليوم','نكتة_تقنية','حكمة','اقتباس_ملوكي','معلومة_تقنية','تحفيز','مود_البوت','فكرة_اليوم'];
