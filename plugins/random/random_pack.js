const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];

const EMOJIS = ['🔥','😂','🥷','👑','🐉','💎','⚡','🎯','🚀','🎭','🦾','🍀','🕶️','🛸','🎮'];
const COLORS = ['🔴 أحمر','🔵 أزرق','🟢 أخضر','🟡 أصفر','🟣 بنفسجي','⚫ أسود','⚪ أبيض','🟠 برتقالي','🟤 بني'];
const NAMES  = ['كريم','محمد','أحمد','يوسف','عمر','مصطفى','زياد','سيف','مازن','آدم','ليلى','سارة','ملك','نور','جنى'];
const YESNO  = [
    '✅ أيوه يا لورد، طلقة اتصرفت.',
    '❌ لأ يا صايع، السيستم رافض النقطة دي.',
    '🤷‍♂️ يمكن... رمي عملة تاني وشوف.',
    '🔥 أكيد جدًا، متردّدش خالص.',
    '⛔ إيرور! دي فكرة وحشة سيبها.',
    '💯 ماشي يا فنان، كملها على طول.'
];
const FORTUNES = [
    '🍀 النهاردة يومك هيبقى سيستم شغال بلا إيرور.',
    '⚡ بلوك من الحظ الطائر نازل عليك دلوقتي.',
    '🔥 حظك حلو النهاردة، طلقة ورا التانية.',
    '😴 خد بالك، فيه باج صغير هيحصل بس هيتحل بسرعة.',
    '👑 إنت ملك اليوم، تصرف على أساس كده.',
    '🎯 توقيتك مظبوط 100%، امشي في الخطة اللي في دماغك.'
];

const handler = async (m, { command, text }) => {
    switch (command) {

        case 'عشوائي_رقم': case 'رقم_عشوائي': {
            const max = parseInt((text || '').trim()) || 100;
            const n = Math.floor(Math.random() * max) + 1;
            return m.reply(`🎲 *يا فنان، السيستم طلع الرقم:* *${n}*\n_(من 1 لـ ${max})_`);
        }

        case 'قرر': case 'يلا_قرر': {
            return m.reply(`🧠 *قرار السيستم:*\n${pick(YESNO)}`);
        }

        case 'عشوائي_ايموجي': {
            return m.reply(`${pick(EMOJIS)} *دي الطلقة اللي طلعتلك يا صايع*`);
        }

        case 'دور_عجلة': case 'اختارلي': {
            const opts = (text || '').split(',').map(s => s.trim()).filter(Boolean);
            if (opts.length < 2) {
                return m.reply('*⚠️ اكتب خيارين على الأقل مفصولين بفاصلة*\n_مثال:_ `.دور_عجلة بيتزا, برجر, شاورما`');
            }
            return m.reply(`🎡 *العجلة لفت ووقفت على:*\n👉 *${pick(opts)}*\n\n_مفيش نقاش، السيستم قرر._`);
        }

        case 'عشوائي_لون': {
            return m.reply(`🎨 *اللون اللي نزلك النهاردة:*\n${pick(COLORS)}`);
        }

        case 'رمي_نرد': {
            const d = Math.floor(Math.random() * 6) + 1;
            const faces = ['⚀','⚁','⚂','⚃','⚄','⚅'];
            return m.reply(`${faces[d-1]} *النرد وقف على رقم ${d}*`);
        }

        case 'عشوائي_حرف': {
            const letters = 'أبتثجحخدذرزسشصضطظعغفقكلمنهوي'.split('');
            return m.reply(`🔤 *الحرف اللي طلع:* *${pick(letters)}*`);
        }

        case 'عشوائي_اسم': {
            return m.reply(`👤 *اسم عشوائي من السيستم:* *${pick(NAMES)}*`);
        }

        case 'توقعاتي': case 'حظي': {
            return m.reply(`🔮 *توقعات النهاردة يا لورد:*\n${pick(FORTUNES)}`);
        }

        case 'اختار_بيني': case 'انا_وهو': {
            const opts = ['إنت', 'هو', 'محدش فيكم دلوقتي 😂'];
            return m.reply(`⚖️ *السيستم حلل الموضوع وقرر:*\n👉 *${pick(opts)}*`);
        }
    }
};

handler.usage = [
    'عشوائي_رقم <حد>','قرر','عشوائي_ايموجي','دور_عجلة <خيارات,مفصولة,بفاصلة>',
    'عشوائي_لون','رمي_نرد','عشوائي_حرف','عشوائي_اسم','توقعاتي','اختار_بيني'
];
handler.category = 'random';
handler.command  = [
    'عشوائي_رقم','رقم_عشوائي','قرر','يلا_قرر','عشوائي_ايموجي',
    'دور_عجلة','اختارلي','عشوائي_لون','رمي_نرد',
    'عشوائي_حرف','عشوائي_اسم','توقعاتي','حظي','اختار_بيني','انا_وهو'
];

export default handler;
