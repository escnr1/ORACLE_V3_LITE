const rnd = arr => arr[Math.floor(Math.random() * arr.length)];

const handler = async (m, { conn, command }) => {
    const map = { نكتة: JOKES, معلومة: FACTS, اقتباس: QUOTES, سؤال_عشوائي: QUESTIONS };
    const list = map[command];
    if (!list) return;

    const emoji = { نكتة: '😂', معلومة: 'ℹ️', اقتباس: '💬', سؤال_عشوائي: '❓' }[command];

    return conn.sendMessage(m.chat, {
        text: `${emoji} ${rnd(list)}`
    }, { quoted: m });
};

handler.usage    = ['نكتة', 'معلومة', 'اقتباس', 'سؤال_عشوائي'];
handler.category = 'fun';
handler.command  = ['نكتة', 'معلومة', 'اقتباس', 'سؤال_عشوائي'];
handler.cooldown = 2000;

export default handler;
